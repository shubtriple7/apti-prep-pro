export const QUESTION_BANK: Question[] = [
  ...aptitude,
  ...verbal,
  ...hr,
  ...technical,
  ...business,
];

export const QUESTIONS_BY_ID = Object.fromEntries(
  QUESTION_BANK.map((item) => [item.id, item]),
) as Record<string, Question>;

export function byCategory(category: Category) {
  return QUESTION_BANK.filter((item) => item.category === category);
}

/** Deterministic daily set builder — content changes, code does not. */
export function buildDailySet(day: number) {
  const pick = (category: Category, count: number, offset: number) => {
    const pool = byCategory(category);
    return Array.from({ length: count }, (_, i) => {
      const item = pool[(offset + i) % pool.length];
      return item!.id;
    });
  };
  const seed = (day - 1) * 2;
  return {
    day,
    morning: [
      ...pick("business", 2, seed),
      ...pick("aptitude", 2, seed),
      ...pick("verbal", 2, seed),
      ...pick("hr", 2, seed),
      ...pick("technical", 2, seed),
    ],
    evening: [
      ...pick("aptitude", 2, seed + 4),
      ...pick("technical", 3, seed + 4),
      ...pick("verbal", 2, seed + 4),
      ...pick("business", 2, seed + 4),
      ...pick("hr", 1, seed + 4),
    ],
  };
}

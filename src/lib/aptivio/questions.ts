import type { Category, Difficulty, Question, QuestionType } from "./types";

let counter = 0;

function q(
  category: Category,
  difficulty: Difficulty,
  question: string,
  options: string[],
  correctAnswer: number | number[],
  explanation: string,
  companyTags: string[] = [],
  type: QuestionType = "mcq",
): Question {
  counter += 1;
  return {
    id: `${category}-${String(counter).padStart(3, "0")}`,
    category,
    difficulty,
    companyTags,
    question,
    options,
    correctAnswer,
    type,
    explanation,
    sourceType: "authored",
  };
}

